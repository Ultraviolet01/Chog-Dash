#!/usr/bin/env node
/*
 * Writes js/pool-artifact.js (the pool contract's ABI and bytecode, used by the admin page to deploy it from the
 * owner's wallet and by the game to buy tickets) from Foundry's build output.
 *   forge build && node scripts/build-pool.js
 */
const fs = require("fs");
const path = require("path");
const out = path.join(__dirname, "../contracts/out/ChogDashPool.sol/ChogDashPool.json");
const j = JSON.parse(fs.readFileSync(out, "utf8"));
const meta = typeof j.rawMetadata === "string" ? JSON.parse(j.rawMetadata) : j.metadata;
const artifact = {
  contract: "ChogDashPool",
  compiler: meta && meta.compiler ? meta.compiler.version : null,
  settings: meta ? { optimizer: meta.settings.optimizer, evmVersion: meta.settings.evmVersion } : null,
  abi: j.abi,
  bytecode: j.bytecode.object,
};
const body = "/* Generated by scripts/build-pool.js from contracts/ChogDashPool.sol. Do not edit. */\n" +
  "(function (root, factory) {\n  if (typeof module === \"object\" && module.exports) module.exports = factory();\n  else root.ChogPoolArtifact = factory();\n" +
  "})(typeof self !== \"undefined\" ? self : this, function () {\n  return " + JSON.stringify(artifact) + ";\n});\n";
fs.writeFileSync(path.join(__dirname, "../js/pool-artifact.js"), body);
console.log("js/pool-artifact.js:", artifact.abi.length, "ABI entries,", (artifact.bytecode.length - 2) / 2, "bytes, solc", artifact.compiler);
